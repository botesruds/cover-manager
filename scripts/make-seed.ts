// Usage:
//   node --experimental-strip-types scripts/make-seed.ts <rota.xlsx> [timetable.xlsx] > supabase/seed.sql
import { readFileSync } from "node:fs";
import { readRotaWorkbook, readTimetableWorkbook } from "../lib/workbook.ts";
import { toImportPayload } from "../lib/rota-parse.ts";

const [rotaFile, ttFile] = process.argv.slice(2);
if (!rotaFile) {
  console.error("Usage: make-seed.ts <rota.xlsx> [timetable.xlsx]");
  process.exit(1);
}
const load = (f: string) => new Uint8Array(readFileSync(f)).buffer;
const lit = (v: unknown) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;

const rota = await readRotaWorkbook(load(rotaFile));
for (const p of rota.problems) console.error("rota warning:", p);
console.error(`Rota: ${rota.rows.length} staff from "${rota.source}".`);

const out: string[] = [
  "-- Generated by scripts/make-seed.ts from the cover rota (and master timetable) spreadsheets.",
  "-- Loads staff, rota slots and timetable free periods without needing a signed-in user.",
  "begin;",
  `create temp table _rota as select * from jsonb_to_recordset(${lit(toImportPayload(rota.rows))})
  as x(code text, name text, teaches text, slots jsonb);`,
  `insert into public.staff (code, name, teaches)
  select code, name, teaches from _rota
  on conflict (code) do update set name = excluded.name, teaches = excluded.teaches, active = true;`,
  `delete from public.rota_slots;`,
  `insert into public.rota_slots (staff_id, kind, day, period, option)
  select s.id, sl->>'kind', (sl->>'day')::smallint, sl->>'period', nullif(sl->>'option','')::smallint
  from _rota r join public.staff s on s.code = r.code
  cross join lateral jsonb_array_elements(r.slots) sl
  on conflict (staff_id, day, period) do nothing;`,
];

if (ttFile) {
  const tt = await readTimetableWorkbook(load(ttFile));
  for (const p of tt.problems) console.error("timetable warning:", p);
  console.error(`Timetable: ${tt.staff.length} staff.`);
  const payload = tt.staff.map((s) => ({ code: s.code, name: s.name, free: s.free }));
  out.push(
    `create temp table _tt as select * from jsonb_to_recordset(${lit(payload)}) as x(code text, name text, free jsonb);`,
    `insert into public.staff (code, name) select code, name from _tt on conflict (code) do nothing;`,
    `delete from public.timetable_free;`,
    `insert into public.timetable_free (staff_id, week, day, period)
  select s.id, w.key, split_part(v, '-', 1)::smallint, split_part(v, '-', 2)
  from _tt t join public.staff s on s.code = t.code
  cross join lateral jsonb_each(t.free) w
  cross join lateral jsonb_array_elements_text(w.value) v
  on conflict do nothing;`,
  );
}
out.push("commit;");
console.log(out.join("\n"));
