// Usage: node --experimental-strip-types scripts/make-seed.ts <rota.xlsx> > supabase/seed.sql
import { readFileSync } from "node:fs";
import { readRotaWorkbook } from "../lib/workbook.ts";
import { toImportPayload } from "../lib/rota-parse.ts";

const file = process.argv[2];
if (!file) {
  console.error("Usage: make-seed.ts <rota.xlsx>");
  process.exit(1);
}
const buf = readFileSync(file);
const ab = new Uint8Array(buf).buffer;
const { rows, problems, source } = await readRotaWorkbook(
  ab,
);
for (const p of problems) console.error("warning:", p);
console.error(`Read ${rows.length} staff from "${source}".`);

const json = JSON.stringify(toImportPayload(rows)).replace(/'/g, "''");
const lines: string[] = [];
lines.push("-- Generated by scripts/make-seed.ts from the cover rota spreadsheet.");
lines.push("-- Loads staff and rota slots without needing a signed-in user.");
lines.push("begin;");
lines.push(`create temp table _rota as select * from jsonb_to_recordset('${json}'::jsonb)`);
lines.push("  as x(code text, name text, teaches text, slots jsonb);");
lines.push(`insert into public.staff (code, name, teaches)
  select code, name, teaches from _rota
  on conflict (code) do update set name = excluded.name, teaches = excluded.teaches, active = true;`);
lines.push(`insert into public.rota_slots (staff_id, kind, day, period, option)
  select s.id, sl->>'kind', (sl->>'day')::smallint, sl->>'period', nullif(sl->>'option','')::smallint
  from _rota r join public.staff s on s.code = r.code
  cross join lateral jsonb_array_elements(r.slots) sl
  on conflict (staff_id, day, period) do nothing;`);
lines.push("commit;");
console.log(lines.join("\n"));
